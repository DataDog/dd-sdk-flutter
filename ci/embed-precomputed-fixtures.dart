// Generates portable fixture text without parsing or rounding JSON numbers.
import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  final root = File.fromUri(Platform.script).parent.parent;
  final fixtures = Directory(
    '${root.path}/packages/datadog_flags/test/fixtures/precomputed',
  );
  final output = File('${fixtures.parent.path}/precomputed_text.dart');
  final paths =
      (jsonDecode(File('${fixtures.path}/index.json').readAsStringSync())
              as List)
          .cast<String>();
  String literal(String text) => jsonEncode(text).replaceAll(r'$', r'\$');
  final buffer =
      StringBuffer(
          '// Generated by ci/embed-precomputed-fixtures.dart. Do not edit.\n// ignore_for_file: type=lint\n// dart format off\n',
        )
        ..writeln(
          'const precomputedRevision = ${literal((jsonDecode(File('${fixtures.path}/SOURCE.json').readAsStringSync()) as Map)['commit'] as String)};',
        )
        ..writeln(
          'const precomputedText = <String, ({String fixture, String response})>{',
        );
  for (final path in paths) {
    buffer.writeln(
      '${literal(path)}: (fixture: ${literal(File('${fixtures.path}/$path').readAsStringSync())}, response: ${literal(File('${fixtures.path}/responses/$path').readAsStringSync())}),',
    );
  }
  buffer.writeln('};');
  final text = buffer.toString();
  if (args.contains('--check')) {
    if (!output.existsSync() || output.readAsStringSync() != text) {
      throw StateError(
        'Regenerate embedded fixtures with dart ci/embed-precomputed-fixtures.dart',
      );
    }
  } else {
    output.writeAsStringSync(text);
  }
}
