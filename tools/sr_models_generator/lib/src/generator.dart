import 'dart:io';

import 'package:path/path.dart' as p;

import 'config.dart';
import 'model.dart';
import 'printer.dart';
import 'resolver.dart';
import 'schema_loader.dart';

/// The generated models library.
typedef GeneratedLibrary = ({String code, List<Definition> definitions});

/// Generates the models of the [config]'s root schemas, read from
/// [schemasRoot] (a rum-events-format checkout), as a formatted Dart
/// library. [source] says where the schemas come from, in the header.
Future<GeneratedLibrary> generateLibrary(
  GeneratorConfig config, {
  required String schemasRoot,
  required String source,
}) async {
  final resolver = ModelResolver(
    SchemaLoader(schemasRoot, mounts: config.schemaMounts),
    naming: config.naming,
  );
  resolver.resolveRoots(config.rootSchemas);
  final definitions = resolver.definitions;
  final code = DartPrinter(
    header: [
      'Unless explicitly stated otherwise all files in this repository are '
          'licensed under the Apache License Version 2.0.',
      'This product includes software developed at Datadog '
          '(https://www.datadoghq.com/).',
      'Copyright 2026-Present Datadog, Inc.',
      '',
      'GENERATED CODE - DO NOT MODIFY BY HAND.',
      'Generated by tools/sr_models_generator from the schemas at',
      source,
    ],
  ).printLibrary(definitions);
  return (
    code: await formatDart(code, destination: config.output),
    definitions: definitions,
  );
}

/// [code] formatted by `dart format` as it would be at [destination], so
/// that the language version and settings of its package apply.
///
/// Throws a [StateError] with the formatter output when [code] does not
/// parse.
Future<String> formatDart(String code, {required String destination}) async {
  var directory = p.dirname(p.absolute(destination));
  while (!Directory(directory).existsSync()) {
    directory = p.dirname(directory);
  }
  final scratch = Directory(directory).createTempSync('.sr_models_generator_');
  try {
    final file = File(p.join(scratch.path, p.basename(destination)))
      ..writeAsStringSync(code);
    final result = await Process.run('dart', ['format', file.path]);
    if (result.exitCode != 0) {
      throw StateError(
        'dart format failed (exit code ${result.exitCode}):\n'
        '${result.stdout}${result.stderr}',
      );
    }
    return file.readAsStringSync();
  } finally {
    scratch.deleteSync(recursive: true);
  }
}
